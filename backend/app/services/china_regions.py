def extract_target_province(text: str) -> str:
    """从任意文本中提取命中的目标省份(四川/西藏/新疆)。未命中返回空串。
    用于中标/线索地域过滤: 命中目标省市级/县级词即归属该省。

    防误命中:
      1. 外部省名优先排除 — 文本含明确非目标省名(如「广西壮族自治区」「河南省」)
         直接返回空, 避免重名县区词误判(如 内江东兴区 vs 广西东兴市)
      2. 市级/县级词用「词前非中文」正则(左边界)匹配, 避免嵌字误判
         (如 长春"市中心"→市中、上高县→高县、舟山"山南北部"→山南)
    """
    import re as _re
    if not text:
        return ""
    # 0) 外部省名优先排除: 明确出现非目标省全名/核心词 → 非目标省
    for _pc, _pl, _cs in _CHINA_REGIONS:
        if _pc in TARGET_PROVINCES:
            continue
        if _pl and _pl in text:
            return ""
    # 1) 直接命中目标省核心词
    for prov in TARGET_PROVINCES:
        if prov in text:
            return prov
    # 2) 市级词(目标省) + 左边界: 如 成都/阿坝/乌鲁木齐/山南
    for c, prov in _CITY_OF.items():
        if prov not in TARGET_PROVINCES:
            continue
        if _re.search(rf"(?<![\u4e00-\u9fa5]){_re.escape(c)}", text):
            return prov
    # 3) 县级词(目标省) + 左边界: 如 茂县/威远/塔什库尔干
    for city_key, counties in REGION_COUNTIES.items():
        pc = _CITY_OF.get(city_key) or ""
        if pc not in TARGET_PROVINCES:
            continue
        for ct in counties:
            if _re.search(rf"(?<![\u4e00-\u9fa5]){_re.escape(ct)}", text):
                return pc
    return ""


