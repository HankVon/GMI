def province_core(name: str) -> Optional[str]:
    """任意文本 → 省核心词(四川); 未命中返回 None。"""
    if not name:
        return None
    # 完整省名或核心词
    for p, pl, _c in _CHINA_REGIONS:
        if name in (p, pl) or pl.startswith(name) or name in pl:
            return p
    return None


def city_core(name: str) -> Optional[str]:
    """任意文本 → 市核心词(成都); 未命中返回 None。"""
    if not name:
        return None
    for c in _CITY_OF:
        if name == c or name == f"{c}市" or name == f"{c}地区" or name == f"{c}自治州" \
           or name == f"{c}盟" or name == f"{c}州" or name == f"{c}回族自治州" \
           or name == f"{c}蒙古自治州" or name == f"{c}市辖区":
            return c
    return None


def county_core(name: str) -> Optional[str]:
    """任意文本 → 县核心词(喜德); 未命中返回 None。"""
    if not name:
        return None
    for city, counties in REGION_COUNTIES.items():
        for ct in counties:
            if name == ct or name == f"{ct}县" or name == f"{ct}区" or name == f"{ct}市" or name == f"{ct}旗":
                return ct
    return None


def resolve_region(province: str = "", city: str = "", county: str = "") -> dict:
    """把省/市/县(任意写法) 解析为三级标准结构。

    返回 {"province": 省核心, "province_label": 省全名, "city": 市核心,
          "city_label": 市全名, "county": 县核心, "county_label": 县全名,
          "matched": bool}  — 任何一级匹配成功 matched=True。
    """
    p = province_core(province)
    c = city_core(city)
    ct = county_core(county)
    # 省市级联: 若只给了市, 反查省
    if not p and c:
        p = _CITY_OF.get(c)
    # 县级反查市级
    if not c and ct:
        for city_key, counties in REGION_COUNTIES.items():
            if ct in counties:
                c = city_key
                p = _CITY_OF.get(city_key)
                break
    # 兜底: 从城市名反查省份
    if c and not p:
        p = _CITY_OF.get(c)
    city_label = _SPECIAL_CITY.get(c or "", "") or (
        f"{c}市" if c and not c.endswith(("州", "盟", "地区", "市")) else (c or ""))
    return {
        "province": p or "",
        "province_label": _PROV_LABELS.get(p, "") if p else "",
        "city": c or "",
        "city_label": city_label,
        "county": ct or "",
        "county_label": f"{ct}县" if ct and not ct.endswith(("区", "县", "市", "旗")) else (ct or ""),
        "matched": bool(p or c or ct),
    }


def all_provinces() -> list:
    """省核心词列表(兼容旧调用 CHINA_PROVINCES)。"""
    return [p for p, _pl, _c in _CHINA_REGIONS]


def target_region_tree() -> list:
    """四川/西藏/新疆 省-市-县 三级树(供前端地域级联选择器)。

    返回: [ {value: 四川, label: 四川省, children: [
            {value: 成都, label: 成都市, children: [{value: 锦江, label: 锦江区}, ...]}]} ]
    value 均为核心词(不带省/市/县后缀), label 为展示全名。
    """
    tree = []
    for prov in TARGET_PROVINCES:
        prov_label = TARGET_PROVINCE_LABELS.get(prov, prov)
        # 该省下辖市(核心词)
        city_cores = [c for c, p in _CITY_OF.items() if p == prov]
        city_nodes = []
        for c in city_cores:
            # 市级全名(特殊区划用全名)
            special = _SPECIAL_CITY.get(c, "")
            city_label = special if special else (f"{c}市" if not c.endswith(("州", "盟", "地区", "市")) else c)
            counties = REGION_COUNTIES.get(c, [])
            # 县级 label 直接显示核心词(如 青川/普兰/定日), 避免区/县后缀误标
            county_nodes = [{"value": ct, "label": ct} for ct in counties]
            city_nodes.append({"value": c, "label": city_label, "children": county_nodes})
        tree.append({"value": prov, "label": prov_label, "children": city_nodes})
    return tree
